"""Generate a deterministic toroidal void-and-cluster rank tile (no external assets)."""
from pathlib import Path
import numpy as np

size = 32
n = size * size
y, x = np.indices((size, size))
points = np.stack((y.ravel(), x.ravel()), axis=1)
d = abs(points[:, None] - points[None, :])
d = np.minimum(d, size - d)
kernel = np.exp(-(d * d).sum(axis=2) / (2 * 1.5**2))
rng = np.random.default_rng(7919)
mask = np.zeros(n, dtype=bool)
mask[rng.choice(n, n // 10, replace=False)] = True
energy = kernel @ mask.astype(float)
for _ in range(n * 10):
    cluster = np.argmax(np.where(mask, energy, -np.inf))
    mask[cluster] = False
    energy -= kernel[:, cluster]
    void = np.argmin(np.where(mask, np.inf, energy))
    mask[void] = True
    energy += kernel[:, void]
    if cluster == void:
        break
else:
    raise RuntimeError("Void-and-cluster relaxation did not converge")
seed = mask.copy()
rank = np.zeros(n, dtype=int)
for value in range(int(mask.sum()) - 1, -1, -1):
    i = np.argmax(np.where(mask, energy, -np.inf))
    rank[i] = value
    mask[i] = False
    energy -= kernel[:, i]
mask = seed.copy()
energy = kernel @ mask.astype(float)
for value in range(int(mask.sum()), n // 2):
    i = np.argmin(np.where(mask, np.inf, energy))
    rank[i] = value
    mask[i] = True
    energy += kernel[:, i]
mask = ~mask
energy = kernel @ mask.astype(float)
for value in range(n // 2, n):
    i = np.argmax(np.where(mask, energy, -np.inf))
    rank[i] = value
    mask[i] = False
    energy -= kernel[:, i]
assert len(np.unique(rank)) == n
out = Path(__file__).resolve().parents[1] / "avboit/shaders/VolumeBlueNoise.hlsli"
lines = [
    "// SPDX-License-Identifier: MIT",
    "// Generated by tools/generate_volume_blue_noise.py.",
    "static const uint VolumeBlueNoise[1024] = {",
]
lines += ["    " + ", ".join(map(str, rank[i : i + 16])) + "," for i in range(0, n, 16)]
lines += ["};"]
out.write_text("\n".join(lines) + "\n")
